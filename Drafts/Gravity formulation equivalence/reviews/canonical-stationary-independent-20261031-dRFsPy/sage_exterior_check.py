def monomial(indices):
    out=A.one()
    for i in indices:
        out *= A.gen(i)
    return out


def normal(F):
    F=A(F)
    out=A.zero()
    for indices, coeff in F.monomial_coefficients().items():
        a=SR(coeff).simplify_full()
        if a != 0:
            out += a*monomial(tuple(indices))
    return out


def deriv(F, name, right=False):
    out=A.zero()
    for indices, coeff in A(F).monomial_coefficients().items():
        ids=tuple(indices)
        if name in even:
            out += SR(coeff).diff(even[name])*monomial(ids)
        else:
            j=odd[name]
            if j in ids:
                pos=ids.index(j)
                sign=(-1)**((len(ids)-1-pos) if right else pos)
                out += sign*coeff*monomial(ids[:pos]+ids[pos+1:])
    return normal(out)


def bracket(F,G, retained=False):
    out=A.zero()
    for a,bb in (pairs[:-1] if retained else pairs):
        out += deriv(F,a,True)*deriv(G,bb) - deriv(F,bb,True)*deriv(G,a)
    return normal(out)


def replace(F, even_map=None, odd_map=None):
    even_map={} if even_map is None else even_map
    odd_map={} if odd_map is None else odd_map
    out=A.zero()
    for indices, coeff in A(F).monomial_coefficients().items():
        term=A(SR(coeff).subs(even_map))
        for j in tuple(indices):
            term *= odd_map.get(j,A.gen(j))
        out += term
    return normal(out)

