"""Exact elementary finite-field certificate for an Einstein S5 quintic.

No numerical root or Galois-group routine is used.  The characteristic
polynomial is regenerated by the complete three-body algorithm; its
independent full-primary differential-Casimir check is in verify_nonchiral.py.
"""
from pathlib import Path
import json
import sympy as s
from three_body_nonchiral import exact_spectrum


def poly_pow_mod(base, exponent, modulus_poly):
    out = s.Poly(1, base.gen, modulus=base.get_modulus())
    while exponent:
        if exponent & 1:
            out = (out*base).rem(modulus_poly)
        base = (base*base).rem(modulus_poly)
        exponent //= 2
    return out


def main():
    x = s.Symbol('x')
    item = exact_spectrum(s.Integer(2),6,3)
    f = s.Poly(s.sympify(item['nonzero_residual_characteristic_polynomial']),x)
    f = f.clear_denoms()[1].primitive()[1]
    f17 = s.Poly(f,x,modulus=17).monic()
    q17 = s.Poly(x*x-x+7,x,modulus=17)
    c17 = s.Poly(x**3-x*x+5*x+6,x,modulus=17)
    assert q17*c17 == f17
    assert s.gcd(f17,f17.diff()).degree() == 0
    assert all(q17.eval(r) != 0 for r in range(17))
    assert all(c17.eval(r) != 0 for r in range(17))
    # For degrees two and three, absence of a field root is irreducibility.

    f23 = s.Poly(f,x,modulus=23).monic()
    expected = s.Poly(x**5-4*x**4-4*x**3-9*x*x+6*x-11,x,modulus=23)
    assert f23 == expected
    variable = s.Poly(x,x,modulus=23)
    first = poly_pow_mod(variable,23,f23)-variable
    last = poly_pow_mod(variable,23**5,f23)-variable
    assert s.gcd(first,f23).degree() == 0
    assert last.is_zero
    # Rabin's irreducibility criterion at prime degree five.
    certificate={
        'case':{'Delta':'2','N':3,'P':6,'Q':3},
        'variable':'x=gamma+240, E=6+P+Q+G*gamma+o(G)',
        'primitive_integer_residual_polynomial':str(f.as_expr()),
        'mod17':{'monic_polynomial':str(f17.as_expr()),
                 'factors':[str(q17.as_expr()),str(c17.as_expr())],
                 'root_checks':34,'square_free':True,'cycle_type':[2,3]},
        'mod23':{'monic_polynomial':str(f23.as_expr()),
                 'gcd_f_x23_minus_x':str(s.gcd(first,f23).as_expr()),
                 'x23power5_minus_x_remainder':str(last.as_expr()),
                 'irreducible':True,'cycle_type':[5]},
        'Galois_group':'S5',
        'proof':('The mod17 Frobenius cube is a transposition. The mod23 '
                 'Frobenius is a 5-cycle. Conjugating the transposition by '
                 'the 5-cycle gives a connected graph of transpositions, '
                 'which generate S5.'),
        'consequence':'This energy block has no solution by radicals over the rationals.',
        'scope':'This does not establish absence of integrability or of formulas using other functions.'
    }
    Path(__file__).with_name('galois_obstruction.json').write_text(
        json.dumps(certificate,indent=2)+'\n')
    print(json.dumps(certificate,indent=2))


if __name__=='__main__':
    main()
