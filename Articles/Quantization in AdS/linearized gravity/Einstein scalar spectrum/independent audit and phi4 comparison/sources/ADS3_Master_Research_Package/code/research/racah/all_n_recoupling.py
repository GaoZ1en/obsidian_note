#!/usr/bin/env python3
"""Exact polynomial-free all-N Bose-primary Einstein spectra.

The only dynamical input is the already established two-body Einstein kernel.
All coordinate operations take place in a left-comb coupling basis.  Adjacent
permutations use a local rational Racah recurrence, and Bose symmetrization is
the nested coset factorization, never a sum over N! permutations.  The positive
image is generated by all labelled bad-pair channels; no physical polynomial
or N-variable monomial is constructed.

This completes an implementation gap in the earlier all-N F-move algorithm.
It is an exact backend, not a claim of complete spectral integrability.
"""
from __future__ import annotations

from collections import defaultdict, Counter
from fractions import Fraction as F
from functools import lru_cache
from itertools import product
from math import comb, factorial, prod
import argparse
import json
from pathlib import Path
import time
import sympy as s


@lru_cache(None)
def rf(a, n):
    a = F(a)
    return prod((a+j for j in range(n)), start=F(1))


@lru_cache(None)
def cg_norm(m, a, b):
    return F(factorial(m))*rf(2*a+2*b+m-1, m)/(rf(2*a,m)*rf(2*b,m))


@lru_cache(None)
def racah_swap(common, leaf, total):
    """Swap the two equal leaves in ((common,leaf)_k,leaf) at total M.

    Returns the matrix in the unnormalized canonical CG gauge, whose binary
    coupling is sum_r (-1)^r binom(m,r) R_A^r R_B^(m-r)/((2a)_r(2b)_(m-r)).
    The local Racah polynomial table uses O((M+1)^2) rational operations.
    """
    a, b, M = F(common), F(leaf), int(total)
    if M == 0:
        return ((F(1),),)
    omega = []
    for k in range(M+1):
        omega.append(rf(2*a,k)*rf(M+2*a+4*b-1,k)*rf(-M,k)*rf(2*a+2*b-1,k)
                     /(rf(2*b,k)*rf(1-2*b-M,k)*rf(M+2*a+2*b,k)*factorial(k))
                     *(2*a+2*b+2*k-1)/(2*a+2*b-1))
    # omega_k*g_k/g_0 is the square of this finite rational product.
    # This removes algebraic square roots from the whole tree compiler.
    t=[rf(2*a+2*b,2*k)/(rf(2*b,k)*rf(2*a+2*b+M,k)) for k in range(M+1)]
    alpha, beta, gamma, delta = 2*a-1, 2*b-1, -M-1, 2*a+2*b+M-1
    table = [[F(1)]*(M+1)]
    for k in range(M):
        ak = ((k+alpha+1)*(k+alpha+beta+1)*(k+beta+delta+1)*(k+gamma+1)
              /((2*k+alpha+beta+1)*(2*k+alpha+beta+2)))
        ck = (F(0) if k == 0 else
              F(k)*(k+beta)*(k+alpha-delta)*(k+alpha+beta-gamma)
              /((2*k+alpha+beta)*(2*k+alpha+beta+1)))
        row = []
        for r in range(M+1):
            lam = F(r)*(r+2*a+2*b-1)
            old = table[k-1][r] if k else F(0)
            row.append(((lam+ak+ck)*table[k][r]-ck*old)/ak)
        table.append(row)
    endpoint = F((-1)**M)*rf(2*b,M)/rf(2*a+2*b,M)
    return tuple(tuple(F((-1)**(k+r))*endpoint*omega[k]*t[r]/t[k]*table[k][r]
                       for r in range(M+1)) for k in range(M+1))


@lru_cache(None)
def compositions(total, length):
    if length == 0:
        return ((),) if total == 0 else ()
    if length == 1:
        return ((total,),)
    return tuple((k,)+tail for k in range(total+1)
                 for tail in compositions(total-k,length-1))


@lru_cache(None)
def comb_norm(delta, label):
    h = F(delta)/2
    current, norm = h, F(1)
    for degree in label:
        norm *= cg_norm(degree,current,h)
        current += h+degree
    return norm


@lru_cache(None)
def chiral_swap_column(delta, label, adjacent):
    """Leaf indices are 1-based: adjacent=j means (j,j+1)."""
    if adjacent == 1:
        return ((label,F((-1)**label[0])),)
    h = F(delta)/2
    at = adjacent-2
    common = (adjacent-1)*h+sum(label[:at])
    m = label[at]+label[at+1]
    matrix = racah_swap(common,h,m)
    source = label[at]
    answer = []
    for target in range(m+1):
        value = matrix[target][source]
        if value:
            changed = label[:at]+(target,m-target)+label[at+2:]
            answer.append((changed,value))
    return tuple(answer)


def adjacent_swap(vector, delta, adjacent):
    middle=defaultdict(F)
    for (left,right), value in vector.items():
        for l,lc in chiral_swap_column(delta,left,adjacent):
            middle[l,right]+=value*lc
    out=defaultdict(F)
    for (left,right),value in middle.items():
        if value:
            for r,rc in chiral_swap_column(delta,right,adjacent):
                out[left,r]+=value*rc
    return {key:value for key,value in out.items() if value}


def transpose(vector, delta, i, j):
    if i == j:
        return dict(vector)
    if i > j:
        i,j = j,i
    # Palindromic reduced adjacent word for the transposition (i j).
    path = list(range(i,j))+list(range(j-2,i-1,-1))
    for adjacent in path:
        vector = adjacent_swap(vector,delta,adjacent)
    return vector


def bose_project(vector, delta, n):
    """Pi_n=T_n ... T_2, T_m=(1/m)sum_i U_(i,m), on comb coordinates."""
    for m in range(2,n+1):
        out = defaultdict(F)
        for i in range(1,m+1):
            transformed = transpose(vector,delta,i,m)
            for key,value in transformed.items():
                out[key] += value/F(m)
        vector = {key:value for key,value in out.items() if value}
    return vector


def spectator_project(vector,delta,n):
    """Project leaves 3,...,N only; pair (1,2) labels stay diagonal."""
    for m in range(4,n+1):
        out=defaultdict(F)
        for i in range(3,m+1):
            transformed=transpose(vector,delta,i,m)
            for key,value in transformed.items():
                out[key]+=value/F(m-2)
        vector={key:value for key,value in out.items() if value}
    return vector


@lru_cache(None)
def coordinate_norm(delta, key):
    return comb_norm(delta,key[0])*comb_norm(delta,key[1])


def inner(left, right, delta):
    if len(left)>len(right):
        left,right=right,left
    return sum((value*right.get(key,F(0))*coordinate_norm(delta,key)
                for key,value in left.items()), F(0))


def pair_energy(delta,k,l):
    d=F(delta)
    if (k+l)%2:
        raise ValueError("Only simultaneous Bose pair channels are physical")
    n, spin = min(k,l), abs(k-l)
    h=d+n; mu=d*(d-2); c=h*(h-1); u=4*mu-8*c
    if spin==0:
        if n==0:
            return -4*d*d+2*d*d*(2*d+5)/((2*d-1)*(2*d+1))
        return u*(2*h-2)/(2*h-1)-2*(c+mu)**2/((2*h-3)*(2*h-1)*(2*h+1))
    if spin==2:
        return u+(n+1)*(n+2)*(2*d+n-1)*(2*d+n)/((2*h-1)*(2*h+1)*(2*h+3))
    return u


def pair_residual(delta,k,l):
    d=F(delta)
    return pair_energy(d,k,l)-(4*d*(d-2)-8*(d+l)*(d+l-1))


def baseline(delta,n,q):
    d=F(delta)
    return -2*n*(n-1)*d*d-8*q*(n*d+q-1)


def primary_dimension(n,p,q):
    """Independent exact cycle-index coefficient; no coordinate expansion."""
    def partitions(k,minimum=1):
        if k==0:
            yield ()
        for j in range(minimum,k+1):
            for tail in partitions(k-j,j):
                yield (j,)+tail
    def coef(degree,parts):
        if degree<0:
            return 0
        a=[1]+[0]*degree
        for step in parts:
            for j in range(step,degree+1):
                a[j]+=a[j-step]
        return a[-1]
    answer=F(0)
    for parts in partitions(n):
        z=prod(k**m*factorial(m) for k,m in Counter(parts).items())
        answer += F((coef(p,parts)-coef(p-1,parts))
                    *(coef(q,parts)-coef(q-1,parts)),z)
    if answer.denominator!=1:
        raise ArithmeticError("Nonintegral Molien coefficient")
    return answer.numerator


def bad_labels(n,p,q):
    for l in range(q+1):
        for k in range(min(p,l+2)+1):
            if (k+l)%2:
                continue
            for left in compositions(p-k,n-2):
                for right in compositions(q-l,n-2):
                    yield ((k,)+left,(l,)+right)


def qs(value):
    value=F(value)
    return s.Rational(value.numerator,value.denominator)


def independent_columns(columns):
    """Sparse rational elimination, retaining original-column identities."""
    pivots={}
    indices=[]
    for index,column in enumerate(columns):
        work=dict(column)
        while work:
            pivot=min(work)
            value=work[pivot]
            if pivot not in pivots:
                pivots[pivot]={k:v/value for k,v in work.items()}
                indices.append(index)
                break
            for key,v in pivots[pivot].items():
                work[key]=work.get(key,F(0))-value*v
                if not work[key]:
                    work.pop(key,None)
    return indices


def positive_gram_pivots(gram):
    """Image columns of a PSD rational Gram, using a rank-revealing LDL."""
    size=len(gram); keep=[]; L=[[] for _ in range(size)]; pivots=[]
    for i in range(size):
        pivot=gram[i][i]-sum((L[i][a]**2*pivots[a]
                             for a in range(len(pivots))),F(0))
        if not pivot:
            continue
        if pivot<0:
            raise ArithmeticError("A projected physical Gram has a negative Schur pivot")
        keep.append(i); pivots.append(pivot)
        for j in range(i,size):
            value=gram[j][i]-sum((L[j][a]*L[i][a]*pivots[a]
                                 for a in range(len(pivots)-1)),F(0))
            L[j].append(value/pivot)
    return keep


def action_bose(vector,delta,n):
    """The actual residual on a Bose primary, without its full matrix."""
    diagonal={}
    for key,value in vector.items():
        k,l=key[0][0],key[1][0]
        if (k+l)%2==0 and k<=l+2:
            diagonal[key]=value*pair_residual(delta,k,l)
    result=bose_project(diagonal,delta,n)
    return {key:comb(n,2)*value for key,value in result.items()}


def adjoin_singleton(vector,delta,n,p,q,P,Q):
    """Couple an n-leaf primary of degree (p,q) to one leaf, then Bose-project.

    Returns (labelled_source, unnormalized_Bose_source).  The normalization of
    the binary CG map is retained in the physical comb-coordinate metric.
    """
    if P<p or Q<q:
        raise ValueError("The target degree must include the fixed cluster degree")
    source={(left+(P-p,),right+(Q-q,)):value
            for (left,right),value in vector.items()}
    return source,bose_project(source,delta,n+1)


def positive_matrix(delta,n,p,q,verify=False):
    if n<3 or p<q or q<0:
        raise ValueError("Use N>=3, P>=Q>=0; otherwise exchange chiralities")
    d=F(delta)
    if d<=1:
        raise ValueError("The Einstein-scalar physical scope requires Delta>1")
    raw_labels=list(bad_labels(n,p,q))
    # Complete the Bose fractional-parentage step first, in the smaller
    # pair-fixed subspace.  It reduces the number of full N-leaf transforms.
    partial=[spectator_project({label:F(1)},d,n) for label in raw_labels]
    partial_gram=[[coordinate_norm(d,raw_labels[i])*partial[j].get(raw_labels[i],F(0))
                   for j in range(len(raw_labels))] for i in range(len(raw_labels))]
    spectator_keep=positive_gram_pivots(partial_gram)
    labels=[raw_labels[i] for i in spectator_keep]
    frame_gram=s.Matrix(len(labels),len(labels),lambda i,j:
                        qs(partial_gram[spectator_keep[i]][spectator_keep[j]]))
    # Pi_N Pi_spectator e_i=Pi_N e_i: no second expansion is necessary.
    columns=[bose_project({label:F(1)},d,n) for label in labels]
    size=len(labels); c=comb(n,2)
    # Idempotence gives <Pi e_i,Pi e_j>=<e_i,Pi e_j>.  Thus a Gram entry is
    # one coordinate read, not a sum over the labelled primary dimension.
    raw_gram=[[c*coordinate_norm(d,labels[i])*columns[j].get(labels[i],F(0))
               for j in range(size)] for i in range(size)]
    # Positive-semidefinite LDL image selection costs O(r_aux*rank^2).
    # No elimination on the much taller labelled-primary coordinate matrix.
    keep=positive_gram_pivots(raw_gram)
    rank=len(keep)
    selected=s.Matrix(rank,size,lambda i,j:qs(raw_gram[keep[i]][j]))
    principal=selected[:,keep]
    coeff=principal.inv()*selected if rank else s.zeros(0,size)
    potentials=s.diag(*[qs(pair_residual(d,key[0][0],key[1][0])) for key in labels])
    raw=potentials*frame_gram.inv()*selected.T
    matrix=coeff*raw
    if verify:
        if any(raw_gram[i][j]!=raw_gram[j][i] for i in range(size) for j in range(i)):
            raise ArithmeticError("Coordinate-extracted Bose Gram is not symmetric")
        for vector in columns:
            for j in range(1,n):
                if adjacent_swap(vector,d,j)!=vector:
                    raise ArithmeticError("Bose projection is not invariant")
        if principal*matrix!=matrix.T*principal:
            raise ArithmeticError("Physical positive-image Gram adjointness fails")
    return matrix,principal/F(c),labels,columns,keep


def spectrum(delta,n,p,q,verify=False,states=False):
    started=time.monotonic()
    d=F(delta)
    matrix,gram,labels,columns,keep=positive_matrix(d,n,p,q,verify)
    x=s.Symbol('x'); dim=primary_dimension(n,p,q)
    out={
        'backend':'all-N rational comb/Racah recurrence with nested Bose cosets',
        'Delta':str(d),'N':n,'P':p,'Q':q,
        'labelled_primary_dimension':comb(p+n-2,n-2)*comb(q+n-2,n-2),
        'labelled_bad_pair_auxiliary_dimension':sum(1 for _ in bad_labels(n,p,q)),
        'spectator_Bose_auxiliary_dimension':len(labels),
        'primary_dimension':dim,'positive_rank':matrix.rows,
        'baseline':str(baseline(d,n,q)),
        'baseline_multiplicity':dim-matrix.rows,
        'positive_shift_coefficients':[str(v) for v in matrix.charpoly(x).all_coeffs()],
        'positive_matrix':[[str(v) for v in matrix.row(i)] for i in range(matrix.rows)],
        'physical_gram':[[str(v) for v in gram.row(i)] for i in range(gram.rows)],
        'runtime_seconds':time.monotonic()-started,
        'scope':'Exact rational finite block; no claim of a universal scalar spectral recurrence.'}
    if states:
        out['state_basis']=[{'raw_cg_seed':[list(labels[i][0]),list(labels[i][1])],
                            'bose_comb_coordinates':[
                                [list(key[0]),list(key[1]),str(value)]
                                for key,value in sorted(columns[i].items())]}
                           for i in keep]
    return out


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--delta',default='2')
    parser.add_argument('--n',type=int,required=True)
    parser.add_argument('--p',type=int,required=True)
    parser.add_argument('--q',type=int,default=0)
    parser.add_argument('--verify',action='store_true')
    parser.add_argument('--states',action='store_true')
    parser.add_argument('--output',type=Path)
    args=parser.parse_args()
    out=spectrum(args.delta,args.n,args.p,args.q,args.verify,args.states)
    text=json.dumps(out,indent=2)+'\n'
    if args.output:
        args.output.write_text(text)
    print(text,end='')
